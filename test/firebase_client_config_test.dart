import 'dart:io';

import 'package:flutter_release_doctor/flutter_release_doctor.dart';
import 'package:test/test.dart';

void main() {
  late Directory tempRoot;

  setUp(() async {
    tempRoot =
        await Directory.systemTemp.createTemp('release_doctor_firebase_cfg_');
  });

  tearDown(() async {
    if (await tempRoot.exists()) {
      await tempRoot.delete(recursive: true);
    }
  });

  test(
      'firebase_options.dart FirebaseOptions.apiKey does not produce hard-coded-secret',
      () async {
    final project = await _baseProject(tempRoot, 'firebase_options_ok');
    final lib = Directory('${project.path}${Platform.pathSeparator}lib');
    await lib.create(recursive: true);
    await File('${lib.path}${Platform.pathSeparator}firebase_options.dart')
        .writeAsString('''
// File generated by FlutterFire CLI.
import 'package:firebase_core/firebase_core.dart' show FirebaseOptions;

class DefaultFirebaseOptions {
  static const FirebaseOptions android = FirebaseOptions(
    apiKey: 'AIzaSyDummyClientApiKeyValue0123456789',
    appId: '1:1234567890:android:abcdef',
    messagingSenderId: '1234567890',
    projectId: 'demo-project',
  );
}
''');

    final report = await ReleaseDoctor().check(project);
    expect(
      report.findings.where((f) => f.id == 'hard-coded-secret'),
      isEmpty,
    );
    final info = report.findings.singleWhere(
      (f) => f.id == 'firebase-client-config-detected',
    );
    expect(info.level, FindingLevel.info);
    expect(
      info.detail,
      'Firebase client configuration was detected. Review Google Cloud API restrictions separately.',
    );
    expect(info.file, 'lib/firebase_options.dart');
    expect(info.line, isNotNull);
    expect(report.toConsole(), contains('firebase-client-config-detected'));
    expect(report.toMarkdown(), contains('firebase-client-config-detected'));
    expect(report.toJsonString(), contains('firebase-client-config-detected'));
    expect(
      report.toJsonString(),
      isNot(contains('AIzaSyDummyClientApiKeyValue0123456789')),
    );
    expect(
      report.findings.any((f) => f.id == 'basic-security-scan'),
      isTrue,
    );
  });

  test('standard google-services.json does not produce hard-coded-secret',
      () async {
    final project = await _baseProject(tempRoot, 'google_services_ok');
    final androidApp = Directory(
      '${project.path}${Platform.pathSeparator}android'
      '${Platform.pathSeparator}app',
    );
    await androidApp.create(recursive: true);
    await File(
      '${androidApp.path}${Platform.pathSeparator}google-services.json',
    ).writeAsString('''
{
  "project_info": {
    "project_number": "1234567890",
    "project_id": "demo-project"
  },
  "client": [
    {
      "client_info": {
        "mobilesdk_app_id": "1:1234567890:android:abcdef",
        "android_client_info": {
          "package_name": "com.example.app"
        }
      },
      "api_key": [
        {
          "current_key": "AIzaSyDummyGoogleServicesKeyValue012345"
        }
      ]
    }
  ]
}
''');

    final report = await ReleaseDoctor().check(project);
    expect(
      report.findings.where((f) => f.id == 'hard-coded-secret'),
      isEmpty,
    );
    final info = report.findings.singleWhere(
      (f) => f.id == 'firebase-client-config-detected',
    );
    expect(info.level, FindingLevel.info);
    expect(info.file, contains('google-services.json'));
    expect(
      report.toJsonString(),
      isNot(contains('AIzaSyDummyGoogleServicesKeyValue012345')),
    );
  });

  test('standard GoogleService-Info.plist does not produce hard-coded-secret',
      () async {
    final project = await _baseProject(tempRoot, 'google_plist_ok');
    final runner = Directory(
      '${project.path}${Platform.pathSeparator}ios'
      '${Platform.pathSeparator}Runner',
    );
    await runner.create(recursive: true);
    await File(
      '${runner.path}${Platform.pathSeparator}GoogleService-Info.plist',
    ).writeAsString('''
<?xml version="1.0" encoding="UTF-8"?>
<plist version="1.0">
<dict>
  <key>API_KEY</key>
  <string>AIzaSyDummyPlistClientApiKeyValue012345</string>
  <key>GCM_SENDER_ID</key>
  <string>1234567890</string>
  <key>GOOGLE_APP_ID</key>
  <string>1:1234567890:ios:abcdef</string>
</dict>
</plist>
''');

    final report = await ReleaseDoctor().check(project);
    expect(
      report.findings.where((f) => f.id == 'hard-coded-secret'),
      isEmpty,
    );
    final info = report.findings.singleWhere(
      (f) => f.id == 'firebase-client-config-detected',
    );
    expect(info.level, FindingLevel.info);
    expect(info.file, contains('GoogleService-Info.plist'));
    expect(
      report.toJsonString(),
      isNot(contains('AIzaSyDummyPlistClientApiKeyValue012345')),
    );
  });

  test('hard-coded API key in a normal Dart service file is still detected',
      () async {
    final project = await _baseProject(tempRoot, 'service_api_key');
    final lib = Directory('${project.path}${Platform.pathSeparator}lib');
    await lib.create(recursive: true);
    await File('${lib.path}${Platform.pathSeparator}payment_service.dart')
        .writeAsString('''
class PaymentService {
  static const apiKey = 'FAKESECRET_test_only_not_a_real_provider_key_0001';
}
''');

    final report = await ReleaseDoctor().check(project);
    final secret = report.findings.singleWhere(
      (f) => f.id == 'hard-coded-secret',
    );
    expect(secret.level, FindingLevel.warning);
    expect(secret.file, 'lib/payment_service.dart');
    expect(secret.line, isNotNull);
    expect(
      report.findings.where((f) => f.id == 'firebase-client-config-detected'),
      isEmpty,
    );
    expect(
      report.toJsonString(),
      isNot(contains('FAKESECRET_test_only_not_a_real_provider_key_0001')),
    );
  });

  test('private key / service-account JSON is still detected', () async {
    final project = await _baseProject(tempRoot, 'service_account_secret');
    await File(
      '${project.path}${Platform.pathSeparator}service-account.json',
    ).writeAsString('''
{
  "type": "service_account",
  "project_id": "demo-project",
  "private_key_id": "abcdef0123456789abcdef0123456789abcdef01",
  "private_key": "-----BEGIN PRIVATE KEY-----\\nMIIEvgIBADANBgkqhkiG9w0BAQEFAASCBKgwggSkAgEAAoIBAQC7\\n-----END PRIVATE KEY-----\\n",
  "client_email": "demo@demo-project.iam.gserviceaccount.com"
}
''');

    final report = await ReleaseDoctor().check(project);
    final secret = report.findings.singleWhere(
      (f) => f.id == 'hard-coded-secret',
    );
    expect(secret.level, FindingLevel.warning);
    expect(secret.file, 'service-account.json');
    expect(secret.line, isNotNull);
    expect(
      report.toJsonString().toLowerCase(),
      isNot(contains('begin private key')),
    );
    expect(
      report.toConsole().toLowerCase(),
      isNot(contains('miievgibadanbg')),
    );
  });
}

Future<Directory> _baseProject(Directory tempRoot, String name) async {
  final project = Directory('${tempRoot.path}${Platform.pathSeparator}$name');
  await project.create(recursive: true);
  await File('${project.path}${Platform.pathSeparator}pubspec.yaml')
      .writeAsString('''
name: $name
description: Fixture
version: 1.0.0+1
environment:
  sdk: ^3.5.0
''');
  return project;
}
